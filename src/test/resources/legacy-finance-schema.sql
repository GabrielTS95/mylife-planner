CREATE TABLE finance_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1003) PRIMARY KEY,
    amount NUMERIC(38, 2),
    description VARCHAR(255),
    category VARCHAR(255),
    bank VARCHAR(255),
    transaction_date DATE,
    accounting_month DATE,
    registration_date DATE,
    duplicate_source_id BIGINT,
    user_id BIGINT,
    type ENUM('GASTO', 'INGRESO')
);

